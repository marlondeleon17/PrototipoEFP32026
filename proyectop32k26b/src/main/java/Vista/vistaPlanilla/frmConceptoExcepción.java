    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if(txtConcepto.getText().trim().isEmpty() ||
           txtEmpleado.getText().trim().isEmpty()){

            JOptionPane.showMessageDialog(
                    null,
                    "Complete los campos"
            );

            return;
        }

        try {

            clsConceptoExcepción excepcion =
                    new clsConceptoExcepción();

            excepcion.setConCodigo(
                    Integer.parseInt(txtConcepto.getText())
            );

            excepcion.setEmpCodigo(
                    Integer.parseInt(txtEmpleado.getText())
            );

            ConceptoExcepciónDAO dao =
                    new ConceptoExcepciónDAO();

            clsBitacora bitacora =
                    crearBitacora("Insertar excepción");

            int resultado =
                    dao.insertarExcepcion(excepcion, bitacora);

            if(resultado > 0){

                JOptionPane.showMessageDialog(
                        null,
                        "Excepción registrada"
                );

                llenadoDeTablas();

                limpiarTextos();

            }else{

                JOptionPane.showMessageDialog(
                        null,
                        "No se pudo registrar"
                );
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    null,
                    "Ingrese números válidos"
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    "Error: " + e.getMessage()
            );
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed


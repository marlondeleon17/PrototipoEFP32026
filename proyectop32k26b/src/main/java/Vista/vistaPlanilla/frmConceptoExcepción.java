    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
        // TODO add your handling code here:
        Connection conn = null;
        Map p = new HashMap();
        JasperReport report;
        JasperPrint print;
        try {
            conn = Conexion.getConnection();
            report = JasperCompileManager.compileReport(new File("").getAbsolutePath()
                + "/src/main/java/Reportes/ReportesPlanilla/reporteConceptoExcepcion.jrxml");
            print = JasperFillManager.fillReport(report, p, conn);
            JasperViewer view = new JasperViewer(print, false);
            view.setTitle("Reporte Prueba");
            view.setVisible(true);
        } catch (Exception e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnReporteActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        if(txtBuscar.getText().trim().isEmpty()){

            JOptionPane.showMessageDialog(
                    null,
                    "Ingrese un ID"
            );

            return;
        }

        try {

            int id =
                    Integer.parseInt(txtBuscar.getText());

            ConceptoExcepciónDAO dao =
                    new ConceptoExcepciónDAO();

            clsBitacora bitacora =
                    crearBitacora("Buscar excepción");

            clsConceptoExcepción excepcion =
                    dao.obtenerExcepcionPorId(id, bitacora);

            if(excepcion != null){

                txtCodigo.setText(
                        String.valueOf(
                                excepcion.getExcCodigo()
                        )
                );

                txtConcepto.setText(
                        String.valueOf(
                                excepcion.getConCodigo()
                        )
                );

                txtEmpleado.setText(
                        String.valueOf(
                                excepcion.getEmpCodigo()
                        )
                );

            }else{

                JOptionPane.showMessageDialog(
                        null,
                        "Registro no encontrado"
                );
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    null,
                    "Ingrese un número válido"
            );
        }
    }//GEN-LAST:event_btnBuscarActionPerformed


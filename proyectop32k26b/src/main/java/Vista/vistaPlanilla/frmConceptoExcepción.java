    private clsBitacora crearBitacora(String accion) {

        clsBitacora bitacora = new clsBitacora();

        try {

            BitacoraDAO dao = new BitacoraDAO();

            int usuario = 1;

            try {

                usuario = clsUsuarioConectado.getUsuId();

            } catch (Exception e) {

                System.out.println("Usuario no definido");
            }

            bitacora.setUsucodigo(usuario);

            bitacora.setAplcodigo(2);

            bitacora.setBitfecha(dao.fechaActual());

            bitacora.setBitip(
                    java.net.InetAddress.getLocalHost().getHostAddress()
            );

            bitacora.setBitequipo(
                    java.net.InetAddress.getLocalHost().getHostName()
            );

            bitacora.setBitaccion(accion);

        } catch (Exception e) {

            e.printStackTrace();
        }

        return bitacora;
    }

     public void llenadoDeTablas() {

        DefaultTableModel modelo = new DefaultTableModel();

        modelo.addColumn("Codigo Excepcion");
        modelo.addColumn("Codigo Concepto");
        modelo.addColumn("Codigo Empleado");

        tblExcepciones.setModel(modelo);

        ConceptoExcepciónDAO dao =
                new ConceptoExcepciónDAO();

        DefaultTableModel tabla =
                dao.listarExcepcionesEnTabla();

        for (int i = 0; i < tabla.getRowCount(); i++) {

            String[] dato = new String[3];

            dato[0] = tabla.getValueAt(i, 0).toString();
            dato[1] = tabla.getValueAt(i, 1).toString();
            dato[2] = tabla.getValueAt(i, 2).toString();

            modelo.addRow(dato);
        }
    }

